for (const route of routes)
  test("anonymous direct access " + route, async ({ request }) => {
    const r = await request.get(route, { maxRedirects: 0 });
    expect([303, 307, 308]).toContain(r.status());
    expect(r.headers().location).toMatch(/\/login/);
  });
